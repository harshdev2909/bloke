// Generates typed `as const` ABIs for the TS packages from Foundry artifacts.
// Usage: (cd contracts && forge build) && node scripts/gen-abi.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const contracts = ["HumanIndexOracle", "BlokeRegistry", "TestUSDC", "ProtocolConfig", "MarketEngine", "Settler", "SimplePool", "BlokePool", "PoolShare",
  "GraduationLauncher", "BlokeToken", "BlokeDesk", "BlokeV2Pair", "BlokeV2Router", "LPLocker", "VestingStream", "MerkleDistributor", "RepRoots", "BlokeRaise"];
const out = join(root, "packages/shared/src/abi");
mkdirSync(out, { recursive: true });
const index = [];
for (const name of contracts) {
  const art = JSON.parse(readFileSync(join(root, "contracts/out", `${name}.sol`, `${name}.json`), "utf8"));
  // lowerCamel, treating a leading acronym as one word: LPLocker → lpLockerAbi.
  const lead = name.match(/^[A-Z]+(?=[A-Z][a-z]|$)/)?.[0] ?? name[0];
  const id = lead.toLowerCase() + name.slice(lead.length) + "Abi";
  writeFileSync(join(out, `${name}.ts`), `// Generated by scripts/gen-abi.mjs. Do not edit.\nexport const ${id} = ${JSON.stringify(art.abi, null, 2)} as const;\n`);
  index.push(`export { ${id} } from "./${name}.js";`);
}
writeFileSync(join(out, "index.ts"), index.join("\n") + "\n");
console.log(`wrote ${contracts.length} ABIs to ${out}`);
